-- Раздел «Пункты выдачи» админки: пункты выдачи заказов (страница /points,
-- вёрстка по макету Figma). Раньше данные были статикой в коде (lib/pickup-points),
-- у всех пунктов одинаковый бейдж — теперь редактируются в админке, у каждого
-- свой адрес/метро/часы/бейдж-акция. Истина контента витрины — наша админка.
--
-- is_central=true — центральный склад (рендерится отдельной карточкой: телефон
-- из SHOP, «основной», полный сервис). badge — акция пункта («−15% на шиномонтаж»);
-- у центрального — пусто (у него свой бейдж «основной»). note — строка «полный сервис»
-- (только у центрального). Порядок — sort_order ASC, затем id.
CREATE TABLE pickup_points (
    id         BIGSERIAL PRIMARY KEY,
    address    TEXT        NOT NULL,
    metro      TEXT        NOT NULL DEFAULT '',
    hours      TEXT        NOT NULL DEFAULT '',
    badge      TEXT        NOT NULL DEFAULT '', -- акция-бейдж, напр. «−15% на шиномонтаж»
    note       TEXT        NOT NULL DEFAULT '', -- строка услуг центрального склада
    is_central BOOLEAN     NOT NULL DEFAULT false,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    published  BOOLEAN     NOT NULL DEFAULT true,
    updated_by TEXT        NOT NULL DEFAULT '',
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

