function isPureSeason(f: ProductFilters): boolean {
  return (
    Boolean(f.season) &&
    !f.q && !f.width && !f.profile && !f.diameter && !f.brand &&
    !f.price_min && !f.price_max && !f.spikes && !f.runflat
  );
}

