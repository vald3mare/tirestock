import type { City } from "./city";

// Модель доставки по городам. Склад в СПб:
//  • СПб — курьер на следующий день + отправка в регионы через ТК;
//  • другие города (пока Москва) — курьера НЕТ, товар едет из СПб через ТК 2–3 дня
//    (на месте не в наличии). Правка владельца 14.09.2026.

export function cityHasCourier(city: City): boolean {
  return city === "spb";
}

// Строка о доставке для карточки товара / инфо-блоков.
export function deliveryLine(city: City): { title: string; note: string } {
  return cityHasCourier(city)
    ? {
        title: "Доставка курьером",
        note: "На следующий день по СПб — от 400 ₽; в регионы РФ — через транспортную компанию",
      }
    : {
        title: "Доставка из Санкт-Петербурга",
        note: "2–3 дня через транспортную компанию — на месте не в наличии",
      };
}
